#!/usr/bin/env python3
"""Build burned-in narration captions from the TTS word timestamps.

Phrases break at punctuation, carry no trailing punctuation, and are placed on each sequence's
timeline with the same segment table the mixer uses (audio/mix.py), so they follow the edit too.
Writes shots/captions.js:  window.CAPTIONS = { "seq01-02": [[start, end, "text"], ...], ... }
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'audio'))
from mix import SEGMENTS, VO  # noqa: E402

BREAK = set('，。；：！？')
DROP = set('，。；：！？—')
MAX_WIDTH = 24          # in CJK character widths; Latin letters count ~0.55
HOLD, MIN_GAP = 0.25, 0.08


def join(words):
    out = ''
    for w in words:
        w = ''.join(c for c in w if c not in DROP)
        if out and w and (re.match(r'[A-Za-z0-9]', w[0]) and re.search(r'[一-鿿A-Za-z0-9]', out[-1])
                          or re.match(r'[一-鿿]', w[0]) and re.search(r'[A-Za-z0-9]', out[-1])):
            out += ' '
        out += w
    return out.strip()


def width(text):
    return sum(0.55 if re.match(r'[ -~]', c) else 1 for c in text)


def phrases(file, a, b):
    words = [w for s in json.loads((VO / f'{file}.json').read_text(encoding='utf-8'))['sentences'] for w in s.get('words', [])]
    words = [w for w in words if w['startTime'] >= a and (b is None or w['startTime'] < b)]
    cur, out = [], []
    for w in words:
        cur.append(w)
        text = join(x['word'] for x in cur)
        if w['word'][-1:] in BREAK or w['word'] == '—' or width(text) >= MAX_WIDTH:
            if text:
                out.append((cur[0]['startTime'], cur[-1]['endTime'], text))
            cur = []
    if cur and join(x['word'] for x in cur):
        out.append((cur[0]['startTime'], cur[-1]['endTime'], join(x['word'] for x in cur)))
    return out


def build(name):
    caps = []
    for file, a, b, place in SEGMENTS[name]:
        for s, e, text in phrases(file, a, b):
            caps.append([round(place + s - a, 3), round(place + e - a, 3), text])
    caps.sort()
    for k, c in enumerate(caps):           # hold each line a little, without running into the next
        nxt = caps[k + 1][0] if k + 1 < len(caps) else c[1] + 1
        c[1] = round(min(c[1] + HOLD, nxt - MIN_GAP), 3)
    return caps


if __name__ == '__main__':
    data = {name: build(name) for name in SEGMENTS}
    js = '// Generated by tools/make_captions.py from the TTS word timestamps — do not edit by hand.\nwindow.CAPTIONS = ' + json.dumps(data, ensure_ascii=False, indent=1) + ';\n'
    (ROOT / 'shots' / 'captions.js').write_text(js, encoding='utf-8')
    for name, caps in data.items():
        print(name, len(caps), 'lines; longest', max(len(c[2]) for c in caps), 'chars')
        for c in caps:
            print(f'   {c[0]:6.2f}–{c[1]:6.2f}  {c[2]}')
